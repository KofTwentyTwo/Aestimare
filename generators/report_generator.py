         md += "|------|-----------|-------------|---------------|-----------|\n"
         for i, dev in enumerate(top_lines, 1):
            md += f"| {i} | [[Developers/{dev['login']}\\|{dev['login']}]] | {dev['lines_added']:,} | {dev['lines_deleted']:,} | {dev['net_lines']:,} |\n"
      
