#!/usr/bin/env python3
"""
Report Generator - Generates markdown reports from assessment data.
Creates a structured report directory similar to the existing assessment format.
"""

import json
import os
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Any
import logging

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)


class ReportGenerator:
   """Generates assessment reports in markdown format."""

   def __init__(self, config: Dict):
      self.config = config
      self.output_dir = Path(config.get('output_dir', 'reports'))
      self.assessment_name = config.get('assessment', {}).get('name', 'Aestimare Assessment')
      self.organization = config.get('assessment', {}).get('organization', 'Organization')
      self.timestamp = datetime.now().strftime('%Y-%m-%d')

   def generate_all_reports(self, executive_summary: Dict, security: Dict,
                        infrastructure: Dict, cost: Dict, repos: List[Dict],
                        developer_activity: Dict, aws_data: Dict, github_data: Dict):
      """Generate all reports from assessment data."""
      logger.info(f"Generating reports to: {self.output_dir}")

      # Create directory structure
      self._create_directory_structure()

      # Generate reports
      self.generate_executive_summary(executive_summary)
      self.generate_security_report(security)
      self.generate_security_issues(security)
      self.generate_infrastructure_report(infrastructure, aws_data)
      self.generate_cost_report(cost)
      self.generate_repository_reports(repos)
      self.generate_developer_activity_reports(developer_activity)
      self.generate_appendices(aws_data, github_data)

      logger.info("Report generation complete")

   def _create_directory_structure(self):
      """Create the report directory structure."""
      dirs = [
         'Security/Issues',
         'Infrastructure/EC2',
         'Infrastructure/RDS',
         'Infrastructure/Lambda',
         'Infrastructure/S3',
         'Code-Repositories/Repos',
         'Code-Repositories/Product-Lines',
         'Cost-Analysis',
         'Product-Lines',
         'Developer-Activity/Developers',
         'Developer-Activity/Summaries',
         'Appendices',
      ]

      for dir_path in dirs:
         (self.output_dir / dir_path).mkdir(parents=True, exist_ok=True)

