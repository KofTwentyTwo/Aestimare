         md += "## Performance Assessment\n\n"
         perf_tests = performance.get('performance_tests', {})
         md += f"- Performance Tests: {'✅' if perf_tests.get('has_perf_tests') else '❌'}\n"
         
         monitoring = performance.get('monitoring_tools', {})
